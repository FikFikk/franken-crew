// SimulateOptions mengatur simulasi chaos in-process.
type SimulateOptions struct {
	// PolicyPath menunjuk katalog policy/actions.yaml (default "policy/actions.yaml").
	PolicyPath string
	// Monotonic opsional menggantikan jam monotonik nyata untuk latensi refleks (test byte-identik).
	// Tanpa nilai ini latensi adalah waktu proses Go + SQLite yang benar-benar terukur.
	Monotonic func() time.Time
}

// Simulate menjalankan tiga skenario (heap_leak, prompt_injection, zombie_storm) melawan komponen Sentinel asli
// in-process dan menyusun replay dari store SQLite simulasi itu sendiri lewat BuildReplay.
func Simulate(ctx context.Context, opts SimulateOptions) (*Replay, error) {
	env, err := newSimEnv(ctx, opts)
	if err != nil {
		return nil, err
	}
	defer env.close()

	var done []*simScenario
	for _, sc := range env.scenarios() {
		if err := env.run(ctx, sc); err != nil {
			return nil, fmt.Errorf("lab: simulate %s: %w", sc.name, err)
		}
		done = append(done, sc)
	}

	ids := make([]string, 0, len(done))
	for _, sc := range done {
		ids = append(ids, sc.incidentID)
	}
	rep, err := BuildReplay(ctx, env.store, ids, ReplaySource{
		Kind:   SourceKindSimulation,
		Label:  simulationLabel,
		Detail: simulationDetail(opts.Monotonic != nil),
	}, SimulationNode)
	if err != nil {
		return nil, err
	}
	rep.GeneratedAt = env.clock.Now()
	for i, sc := range done {
		rep.Incidents[i].Scenario = sc.name
		rep.Incidents[i].Title = sc.title
	}
	return rep, nil
}

func simulationDetail(injectedMonotonic bool) string {
	latency := "Reflex latency figures are in-process Go and SQLite timings measured with the real monotonic clock, not kernel-to-reflex latency on hardware."
	if injectedMonotonic {
		latency = "Reflex latency figures come from an injected monotonic clock (deterministic test run), not from in-process timing."
	}
	return "Generated by `franken lab simulate` in-process against an in-memory cgroup v2 and procfs fixture driven by a scripted workload model. " +
		"The real Sentinel detector, L1 reflex engine with its TTL scheduler, policy and incident-scope checks, Ed25519 approval verifier, " +
		"forward verification worker logic, and postmortem generator ran on a SQLite incident store. Commands go through a fake systemd/PM2 runner, " +
		"and journal lines and unit status come from fakes. Agent turns are scripted MCP tool calls through an in-process MCP session (claimer franken-sentry), " +
		"and wa-bridge's poll, vote, and per-step Ed25519 token minting are reproduced in-process. Timestamps follow a simulated clock starting " +
		simulationStart.Format(time.RFC3339) + ". " + latency
}

// simEnv merangkai seluruh komponen Sentinel asli di atas fixture MemFS dan jam simulasi.
type simEnv struct {
	tmpDir  string
	clock   *simClock
	mfs     *kernelfs.MemFS
	world   *simWorld
	journal *simJournal
	store   *incident.Store
	reflex  *reflex.Engine
	srv     *mcpserver.Server
	daemon  *sentinel.Daemon
	minter  *approval.Minter
	crew    *mcp.ClientSession
	bridge  *mcp.ClientSession

	bridgeRand io.Reader
	seen       map[string]bool

	cancel  context.CancelFunc
	wg      sync.WaitGroup
	closers []func()
}

func newSimEnv(ctx context.Context, opts SimulateOptions) (_ *simEnv, err error) {
	policyPath := strings.TrimSpace(opts.PolicyPath)
	if policyPath == "" {
		policyPath = filepath.Join("policy", "actions.yaml")
	}
	cat, err := policy.LoadCatalog(policyPath)
	if err != nil {
		return nil, fmt.Errorf("lab: load policy catalog: %w", err)
	}
	tmpDir, err := os.MkdirTemp("", "franken-lab-sim-*")
	if err != nil {
		return nil, fmt.Errorf("lab: create simulation dir: %w", err)
	}

	env := &simEnv{
		tmpDir:     tmpDir,
		clock:      &simClock{now: simulationStart},
		mfs:        kernelfs.NewMemFS(),
		journal:    &simJournal{lines: map[string][]string{}},
		bridgeRand: deterministicStream("bridge"),
		seen:       map[string]bool{},
	}
	defer func() {
		if err != nil {
			env.close()
		}
	}()
	env.closers = append(env.closers, func() { _ = os.RemoveAll(tmpDir) })

	env.world = newSimWorld(env.mfs)
	seedSimFixture(env.mfs, env.world)
	// Proteksi PID membaca /proc fixture, bukan proses milik host yang menjalankan simulasi
	cat.SetProcReader(env.mfs.ReadFile)

	env.store, err = incident.NewStore(filepath.Join(tmpDir, "franken-sentinel.db"))
	if err != nil {
		return nil, fmt.Errorf("lab: open simulation store: %w", err)
	}
	env.closers = append(env.closers, func() { _ = env.store.Close() })
	env.store.SetClock(env.clock.Now)

	seed := sha256.Sum256([]byte("frankencrew-lab/ed25519"))
	priv := ed25519.NewKeyFromSeed(seed[:])
	env.minter, err = approval.NewMinter(priv, env.clock.Now)
	if err != nil {
		return nil, err
	}
	env.minter.SetNonceSource(deterministicStream("nonce"))
	verifier, err := approval.NewVerifier(priv.Public().(ed25519.PublicKey), env.store, env.clock.Now)
	if err != nil {
		return nil, err
	}

	hostTotal := uint64(simHostTotalKB) * 1024
	env.reflex, err = reflex.NewEngine(reflex.EngineConfig{
		Store:             env.store,
		FS:                env.mfs,
		Catalog:           cat,
		PropertyDriver:    &simPropertyDriver{world: env.world, props: map[string]reflex.UnitProperties{}},
		AdmissionDriver:   reflex.NewFSAdmissionDriver(filepath.Join(tmpDir, "run-franken")),
		HostMemTotalBytes: hostTotal,
		Clock:             env.clock.Now,
		IDSource:          deterministicStream("reflex"),
	})
	if err != nil {
		return nil, err
	}

	env.srv, err = mcpserver.New(mcpserver.Config{
		NodeName:      SimulationNode,
		Version:       "lab-simulation",
		Store:         env.store,
		Catalog:       cat,
		Reflex:        env.reflex,
		Verifier:      verifier,
		Runner:        &simRunner{world: env.world, clock: env.clock},
		FS:            env.mfs,
		CgroupRoot:    simCgroupRoot,
		ProcRoot:      simProcRoot,
		JournalReader: env.journal,
		UnitInspector: simUnitInspector{},
		HTTPProber:    simProber{},
		PostmortemDir: filepath.Join(tmpDir, "incidents"),
		// Postmortem otomatis seperti `sentinel serve`; path absolut temp dir disamarkan oleh BuildReplay
		AutoPostmortem: true,
		Clock:          env.clock.Now,
		PM2Owner:       "pi",
		PM2Home:        "/home/pi/.pm2",
		// Ticker worker verifikasi memakai waktu nyata; finalisasi dipicu sinkron oleh skenario agar deterministik
		VerifyPollInterval: 24 * time.Hour,
		IDSource:           deterministicStream("evidence"),
	})
	if err != nil {
		return nil, err
	}
	env.closers = append(env.closers, env.srv.Close)

	env.daemon, err = sentinel.New(sentinel.Config{
		NodeName:   SimulationNode,
		FS:         env.mfs,
		CgroupRoot: simCgroupRoot,
		ProcRoot:   simProcRoot,
		Store:      env.store,
		Catalog:    cat,
		Detector:   detector.NewDetector(detector.Config{NodeName: SimulationNode, HostMemTotalBytes: hostTotal}),
		Reflex:     env.reflex,
		MCPServer:  env.srv,
		Clock:      env.clock.Now,
		Monotonic:  opts.Monotonic,
		IDSource:   deterministicStream("sentinel"),
	})
	if err != nil {
		return nil, err
	}

	runCtx, cancel := context.WithCancel(context.WithoutCancel(ctx))
	env.cancel = cancel
	if env.crew, err = env.connect(runCtx, "kiro-crew-sim"); err != nil {
		return nil, err
	}
	if env.bridge, err = env.connect(runCtx, "wa-bridge-sim"); err != nil {
		return nil, err
	}
	return env, nil
}

// connect membuka sesi MCP in-process baru ke server Sentinel simulasi.
func (e *simEnv) connect(ctx context.Context, name string) (*mcp.ClientSession, error) {
	srvT, cliT := mcp.NewInMemoryTransports()
	e.wg.Add(1)
	go func() {
		defer e.wg.Done()
		_ = e.srv.MCPServer().Run(ctx, srvT)
	}()
	session, err := mcp.NewClient(&mcp.Implementation{Name: name, Version: "1.0.0"}, nil).Connect(ctx, cliT, nil)
	if err != nil {
		return nil, fmt.Errorf("lab: connect %s MCP session: %w", name, err)
	}
	return session, nil
}

func (e *simEnv) close() {
	for _, s := range []*mcp.ClientSession{e.crew, e.bridge} {
		if s != nil {
			_ = s.Close()
		}
	}
	if e.cancel != nil {
		e.cancel()
	}
	e.wg.Wait()
	for i := len(e.closers) - 1; i >= 0; i-- {
		e.closers[i]()
	}
}

