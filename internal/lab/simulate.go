// simScenario adalah satu skenario chaos: model beban kerja plus giliran agen terjadwal relatif terhadap pembukaan insiden.
type simScenario struct {
	name    string
	title   string
	cgroup  *simCgroup
	prepare func(start time.Time)
	steps   []simStep

	// postTicks adalah jumlah tick setelah insiden final; untuk cgroup yang dipakai ulang, simulasi menunggu
	// detektor menutup insiden lebih dulu (hysteresis) agar skenario berikutnya membuka insiden baru.
	postTicks      int
	waitDetector   bool
	incidentID     string
	openTick       int
	planHash       string
	approvalID     string
	tokens         []wabridge.StepToken
	journalEvID    string
	telemetryEvID  string
	finalizeAtTick int
}

// simStep adalah satu giliran agen/bridge pada detik ke-at setelah insiden dibuka.
type simStep struct {
	at int
	do func(ctx context.Context, sc *simScenario) error
}

// run menjalankan satu skenario: 1 tick = 1 detik simulasi (model beban kerja, EvaluateOnce, sweep TTL refleks).
func (e *simEnv) run(ctx context.Context, sc *simScenario) error {
	start := e.clock.Now()
	sc.prepare(start)
	stepIdx := 0
	closedAt := -1
	for k := 1; k <= simMaxTicks; k++ {
		evals, err := e.tick(ctx)
		if err != nil {
			return err
		}
		if sc.incidentID == "" {
			id, err := e.detectNewIncident(ctx, sc)
			if err != nil {
				return err
			}
			if id != "" {
				sc.incidentID, sc.openTick = id, k
			}
		}
		if sc.incidentID != "" {
			rel := k - sc.openTick
			for stepIdx < len(sc.steps) && sc.steps[stepIdx].at <= rel {
				if err := sc.steps[stepIdx].do(ctx, sc); err != nil {
					return fmt.Errorf("step at +%ds: %w", sc.steps[stepIdx].at, err)
				}
				stepIdx++
			}
		}
		if sc.incidentID != "" && stepIdx == len(sc.steps) {
			inc, err := e.store.GetIncident(ctx, sc.incidentID)
			if err != nil {
				return err
			}
			if isTerminalStateName(string(inc.State)) {
				if closedAt < 0 {
					closedAt = k
				}
				detectorClosed := !sc.waitDetector || !evals[sc.cgroup.path].IncidentOpen
				if detectorClosed && k-closedAt >= sc.postTicks {
					return nil
				}
			}
		}
	}
	if sc.incidentID == "" {
		return errors.New("detector never opened an incident")
	}
	return fmt.Errorf("incident %s did not finish within %d ticks", sc.incidentID, simMaxTicks)
}

// tick memajukan jam satu detik, memperbarui fixture, mengevaluasi setiap target seperti sampler 1 Hz Sentinel,
// lalu menjalankan sweep TTL refleks seperti scheduler rollback 1 Hz.
func (e *simEnv) tick(ctx context.Context) (map[string]detector.Evaluation, error) {
	now := e.clock.Advance(time.Second)
	e.world.step(now)
	evals := make(map[string]detector.Evaluation, len(e.world.cgroups))
	for _, c := range e.world.cgroups {
		eval, err := e.daemon.EvaluateOnce(ctx, c.path)
		if err != nil {
			return nil, fmt.Errorf("evaluate %s: %w", c.unit, err)
		}
		evals[c.path] = eval
	}
	if _, err := e.reflex.SweepExpired(ctx); err != nil {
		return nil, fmt.Errorf("sweep reflex TTL: %w", err)
	}
	return evals, nil
}

// detectNewIncident mencari insiden baru milik cgroup skenario yang dibuka detektor asli.
func (e *simEnv) detectNewIncident(ctx context.Context, sc *simScenario) (string, error) {
	list, err := e.store.ListIncidents(ctx, "", 5)
	if err != nil {
		return "", err
	}
	rel := strings.TrimPrefix(sc.cgroup.path, simCgroupRoot)
	for _, inc := range list {
		if inc.Cgroup == rel && !e.seen[inc.ID] {
			e.seen[inc.ID] = true
			return inc.ID, nil
		}
	}
	return "", nil
}

// gap memajukan jam di antara skenario (Sentinel tetap hidup namun tidak ada kejadian menarik).
func (e *simEnv) gap(d time.Duration) {
	e.clock.Advance(d)
}

// --- Giliran agen dan bridge (panggilan MCP tool sungguhan) ---

func callTool[T any](ctx context.Context, session *mcp.ClientSession, name string, args map[string]any) (T, error) {
	var zero T
	res, err := session.CallTool(ctx, &mcp.CallToolParams{Name: name, Arguments: args})
	if err != nil {
		return zero, fmt.Errorf("call %s: %w", name, err)
	}
	if res.IsError {
		return zero, fmt.Errorf("tool %s error: %s", name, toolText(res))
	}
	raw, err := json.Marshal(res.StructuredContent)
	if err != nil {
		return zero, err
	}
	var out T
	if err := json.Unmarshal(raw, &out); err != nil {
		return zero, fmt.Errorf("decode %s output: %w", name, err)
	}
	return out, nil
}

// expectToolError memanggil tool yang harus ditolak Sentinel dan mengembalikan teks galatnya.
func expectToolError(ctx context.Context, session *mcp.ClientSession, name string, args map[string]any) (string, error) {
	res, err := session.CallTool(ctx, &mcp.CallToolParams{Name: name, Arguments: args})
	if err != nil {
		return "", fmt.Errorf("call %s: %w", name, err)
	}
	if !res.IsError {
		return "", fmt.Errorf("tool %s unexpectedly succeeded", name)
	}
	return toolText(res), nil
}

func toolText(res *mcp.CallToolResult) string {
	var b strings.Builder
	for _, c := range res.Content {
		if tc, ok := c.(*mcp.TextContent); ok {
			b.WriteString(tc.Text)
		}
	}
	return b.String()
}

// sentryTriage menjalankan giliran Franken-Sentry: klaim, baca insiden, dan simpan journal sebagai evidence.
func (e *simEnv) sentryClaim(ctx context.Context, sc *simScenario) error {
	claim, err := callTool[mcpserver.IncidentClaimOutput](ctx, e.crew, "incident_claim", map[string]any{"claimer": "franken-sentry", "incident_id": sc.incidentID})
	if err != nil {
		return err
	}
	if !claim.Claimed {
		return fmt.Errorf("incident %s could not be claimed", sc.incidentID)
	}
	got, err := callTool[mcpserver.IncidentGetOutput](ctx, e.crew, "incident_get", map[string]any{"incident_id": sc.incidentID})
	if err != nil {
		return err
	}
	for _, ev := range got.Evidence {
		if ev.Kind == "telemetry_sample" {
			sc.telemetryEvID = ev.ID
		}
	}
	return nil
}

func (e *simEnv) sentryJournal(ctx context.Context, sc *simScenario) error {
	out, err := callTool[mcpserver.JournalTailOutput](ctx, e.crew, "journal_tail", map[string]any{"unit": sc.cgroup.unit, "lines": 50, "incident_id": sc.incidentID})
	if err != nil {
		return err
	}
	if out.EvidenceID == "" {
		return errors.New("journal_tail returned no evidence_id")
	}
	sc.journalEvID = out.EvidenceID
	_, err = callTool[mcpserver.PSIHistoryOutput](ctx, e.crew, "psi_history", map[string]any{"cgroup": strings.TrimPrefix(sc.cgroup.path, simCgroupRoot), "minutes": 5})
	return err
}

// architectSubmit mengirim plan beserta triage Sentry; wantValid menandai apakah Sentinel diharapkan menerima.
func (e *simEnv) architectSubmit(ctx context.Context, sc *simScenario, plan policy.Plan, triage map[string]any, wantValid bool) error {
	plan.IncidentID = sc.incidentID
	out, err := callTool[mcpserver.PlanSubmitOutput](ctx, e.crew, "plan_submit", map[string]any{"incident_id": sc.incidentID, "plan": plan, "triage": triage})
	if err != nil {
		return err
	}
	if out.Valid != wantValid {
		return fmt.Errorf("plan_submit valid=%v, want %v (violations %v)", out.Valid, wantValid, out.Violations)
	}
	if out.Valid {
		sc.planHash = out.PlanHash
	}
	return nil
}

// requestApproval menjalankan Remediator MODE=REQUEST_APPROVAL lalu SendApprovalPoll milik wa-bridge.
func (e *simEnv) requestApproval(ctx context.Context, sc *simScenario) error {
	got, err := callTool[mcpserver.IncidentGetOutput](ctx, e.crew, "incident_get", map[string]any{"incident_id": sc.incidentID})
	if err != nil {
		return err
	}
	if got.PlanHash != sc.planHash {
		return fmt.Errorf("remediator plan_hash check failed: %s != %s", got.PlanHash, sc.planHash)
	}
	// wa-bridge membaca plan otoritatif dari Sentinel, mengirim poll, lalu mencatat transisi WAITING_APPROVAL
	stored, err := callTool[mcpserver.IncidentGetOutput](ctx, e.bridge, "incident_get", map[string]any{"incident_id": sc.incidentID})
	if err != nil {
		return err
	}
	var code [2]byte
	if _, err := io.ReadFull(e.bridgeRand, code[:]); err != nil {
		return err
	}
	sc.approvalID = "APR-" + strings.ToUpper(hex.EncodeToString(code[:]))
	if stored.Incident.State != incident.StateWaitingApproval && incident.CanTransition(stored.Incident.State, incident.StateWaitingApproval) {
		if _, err := callTool[mcpserver.IncidentTransitionOutput](ctx, e.bridge, "incident_transition", map[string]any{
			"incident_id": sc.incidentID,
			"to":          string(incident.StateWaitingApproval),
			"reason":      wabridge.FormatPollSentReason(sc.approvalID, stored.PlanHash),
			"actor":       "wa-bridge",
		}); err != nil {
			return err
		}
	}
	return nil
}

// vote mereproduksi approveAndMintToken milik wa-bridge: verifikasi plan tersimpan lalu satu token per langkah.
func (e *simEnv) vote(ctx context.Context, sc *simScenario, optionID string) error {
	stored, err := callTool[mcpserver.IncidentGetOutput](ctx, e.bridge, "incident_get", map[string]any{"incident_id": sc.incidentID})
	if err != nil {
		return err
	}
	if stored.PlanHash != sc.planHash {
		return errors.New("vote plan hash mismatch")
	}
	var plan policy.Plan
	if err := json.Unmarshal([]byte(stored.Incident.PlanJSON), &plan); err != nil {
		return err
	}
	var opt *policy.PlanOption
	for i := range plan.Options {
		if plan.Options[i].ID == optionID {
			opt = &plan.Options[i]
		}
	}
	if opt == nil {
		return fmt.Errorf("option %s not in stored plan", optionID)
	}
	cur := stored.Incident.State
	if cur != incident.StateWaitingApproval && cur != incident.StateRemediating && incident.CanTransition(cur, incident.StateWaitingApproval) {
		if _, err := callTool[mcpserver.IncidentTransitionOutput](ctx, e.bridge, "incident_transition", map[string]any{
			"incident_id": sc.incidentID, "to": string(incident.StateWaitingApproval),
			"reason": "WhatsApp approval granted for option " + opt.ID, "actor": "wa-bridge",
		}); err != nil {
			return err
		}
	}
	sc.tokens = nil
	for _, st := range opt.Steps {
		tok, _, err := e.minter.Mint(approval.MintRequest{
			IncidentID: sc.incidentID, PlanHash: stored.PlanHash, OptionID: opt.ID,
			ActionName: st.Action, StepIDs: []string{st.ID}, ApproverSender: simApprover,
		})
		if err != nil {
			return err
		}
		sc.tokens = append(sc.tokens, wabridge.StepToken{StepID: st.ID, Action: st.Action, Token: tok})
	}
	return nil
}

// execute menjalankan Remediator MODE=EXECUTE: setiap langkah dengan tokennya sendiri, lalu verify_health sekali.
func (e *simEnv) execute(ctx context.Context, sc *simScenario) error {
	got, err := callTool[mcpserver.IncidentGetOutput](ctx, e.crew, "incident_get", map[string]any{"incident_id": sc.incidentID})
	if err != nil {
		return err
	}
	params, err := stepParams(got.Incident.PlanJSON)
	if err != nil {
		return err
	}
	for _, tok := range sc.tokens {
		if _, err := callTool[mcpserver.ActionExecuteOutput](ctx, e.crew, "action_execute", map[string]any{
			"incident_id": sc.incidentID, "step_id": tok.StepID, "action": tok.Action,
			"params": params[tok.StepID], "approval_token": tok.Token,
		}); err != nil {
			return err
		}
	}
	vh, err := callTool[mcpserver.VerifyHealthOutput](ctx, e.crew, "verify_health", map[string]any{"incident_id": sc.incidentID, "window_seconds": 120, "auto_transition": true})
	if err != nil {
		return err
	}
	if !vh.Pending {
		return fmt.Errorf("verify_health must start a forward window, got %s", vh.Status)
	}
	return nil
}

// finalizeVerification memicu finalisasi worker verifikasi Sentinel tepat saat jendela 120 detik habis
// (ticker waktu nyata worker tidak dipakai agar simulasi deterministik).
func (e *simEnv) finalizeVerification(ctx context.Context, sc *simScenario) error {
	vh, err := callTool[mcpserver.VerifyHealthOutput](ctx, e.crew, "verify_health", map[string]any{"incident_id": sc.incidentID, "window_seconds": 120, "auto_transition": true})
	if err != nil {
		return err
	}
	if vh.Pending {
		return fmt.Errorf("verification still pending (%ds left)", vh.RemainingSeconds)
	}
	return nil
}

func stepParams(planJSON string) (map[string]map[string]any, error) {
	var plan policy.Plan
	if err := json.Unmarshal([]byte(planJSON), &plan); err != nil {
		return nil, fmt.Errorf("decode stored plan: %w", err)
	}
	out := map[string]map[string]any{}
	for _, opt := range plan.Options {
		for _, st := range opt.Steps {
			out[st.ID] = st.Params
		}
	}
	return out, nil
}

