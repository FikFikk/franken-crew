// --- Model beban kerja ---

// leakWorkload memodelkan kebocoran heap PM2: memori datar, kebocoran yang naik bertahap, tekanan PSI yang lega
// setelah refleks reclaim, lalu kembali ke baseline setelah reload/restart worker.
type leakWorkload struct {
	base, rate             float64
	rampDur                time.Duration
	peakStall, reliefStall float64
	restartBase            float64

	trueMem      float64
	leakStart    time.Time
	reliefAt     time.Time
	remediatedAt time.Time
}

func (w *leakWorkload) reset(c *simCgroup, leakStart time.Time) {
	w.trueMem = w.base
	w.leakStart = leakStart
	w.reliefAt, w.remediatedAt = time.Time{}, time.Time{}
	c.mem = w.base
}

func (w *leakWorkload) step(c *simCgroup, now time.Time) {
	if !w.remediatedAt.IsZero() {
		since := now.Sub(w.remediatedAt).Seconds()
		// Worker baru tumbuh sedikit saat warm-up (~1.5 MiB dalam 30 s) lalu datar
		target := w.restartBase + 1.5*mebibyte*(1-math.Exp(-since/30))
		w.trueMem = target + (w.trueMem-target)*math.Exp(-1.0/2)
		c.mem = w.trueMem + jitter(now, 0.06*mebibyte)
		c.someStall = 0.4 + jitter(now, 0.05)
		c.fullStall = 0.05
		return
	}
	w.trueMem += w.rate * ramp(now, w.leakStart, w.rampDur)
	c.mem = w.trueMem + jitter(now, 0.25*mebibyte)
	if w.reliefAt.IsZero() {
		c.someStall = 0.35 + (w.peakStall-0.35)*ramp(now, w.leakStart, 50*time.Second) + jitter(now, 0.15)
	} else {
		c.someStall = w.reliefStall + 1.2*ramp(now, w.reliefAt, 80*time.Second) + jitter(now, 0.1)
	}
	c.fullStall = 0.17 * c.someStall
}

func (w *leakWorkload) onReclaim(_ *simCgroup, now time.Time, bytes float64) {
	w.trueMem = math.Max(w.trueMem-bytes, w.base)
	if w.reliefAt.IsZero() {
		w.reliefAt = now
	}
}

func (w *leakWorkload) onCommand(_ *simCgroup, now time.Time, binary string, args []string) {
	joined := binary + " " + strings.Join(args, " ")
	if strings.Contains(joined, " pm2 reload ") || strings.Contains(joined, " pm2 restart ") || strings.HasPrefix(joined, "systemctl restart ") {
		w.remediatedAt = now
	}
}

// zombieWorkload memodelkan job-runner yang berhenti me-reap anak: zombie Z bertambah di /proc dan buffer hasil
// job tumbuh; SIGCHLD me-reap zombie tetapi memori tetap naik karena buffer tidak pernah di-flush.
type zombieWorkload struct {
	mfs                       *kernelfs.MemFS
	parentPID, firstPID       int
	base, rate, postRate      float64
	rampDur                   time.Duration
	trueMem                   float64
	growStart, zombiesFrom    time.Time
	reapedAt, lastZombieSpawn time.Time
	zombies                   map[int]bool
	nextPID                   int
}

func (w *zombieWorkload) reset(c *simCgroup, growStart, zombiesFrom time.Time) {
	w.trueMem, w.growStart, w.zombiesFrom = w.base, growStart, zombiesFrom
	w.reapedAt, w.lastZombieSpawn = time.Time{}, time.Time{}
	w.zombies = map[int]bool{}
	w.nextPID = w.firstPID
	c.mem = w.base
	for i := 0; i < 6; i++ {
		w.spawnZombie()
	}
}

func (w *zombieWorkload) spawnZombie() {
	pid := w.nextPID
	w.nextPID++
	w.zombies[pid] = true
	setProc(w.mfs, pid, w.parentPID, "job", "Z", "", "/franken.slice/worker.service", 0)
}

func (w *zombieWorkload) zombieCount() int { return len(w.zombies) }

func (w *zombieWorkload) step(c *simCgroup, now time.Time) {
	if w.reapedAt.IsZero() {
		if !now.Before(w.zombiesFrom) && now.Sub(w.lastZombieSpawn) >= 3*time.Second {
			w.spawnZombie()
			w.lastZombieSpawn = now
		}
		w.trueMem += w.rate * ramp(now, w.growStart, w.rampDur)
	} else {
		w.trueMem += w.postRate
	}
	c.mem = w.trueMem + jitter(now, 0.12*mebibyte)
	u := c.mem / float64(c.maxBytes)
	c.someStall = 0.5 + 3.0*math.Max(0, u-0.5)/0.4 + jitter(now, 0.08)
	c.fullStall = 0.12 * c.someStall
}

func (w *zombieWorkload) onReclaim(_ *simCgroup, _ time.Time, bytes float64) {
	w.trueMem = math.Max(w.trueMem-bytes, w.base)
}

func (w *zombieWorkload) onCommand(_ *simCgroup, now time.Time, binary string, args []string) {
	if binary == "kill" && len(args) >= 2 && args[0] == "-CHLD" && args[1] == fmt.Sprint(w.parentPID) {
		w.reapedAt = now
		for _, pid := range sortedKeys(w.zombies) {
			removeProc(w.mfs, pid)
		}
		w.zombies = map[int]bool{}
	}
}
